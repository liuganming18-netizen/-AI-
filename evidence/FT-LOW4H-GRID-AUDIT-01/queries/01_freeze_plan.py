def main() -> None:
    L.OUT.mkdir(parents=True, exist_ok=True)
    st = L.up_state()
    combos, names, rows = L.discover_groups()
    plan = dict(PLAN)
    plan["冻结时刻"] = datetime.now(CST).isoformat(timespec="seconds")
    plan["冻结时上游状态"] = st
    plan["冻结时发现的组合数"] = len(combos)
    plan["冻结时发现的策略文件数"] = len(rows)
    plan["冻结时已落盘逐笔结果数"] = st["逐笔结果文件数"]
    plan["上游是否已产出"] = st["可用"]
    plan["本脚本SHA256"] = sha_file(__file__)

    p = L.OUT / "01_冻结分析计划.json"
    p.write_text(json.dumps(plan, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    h = hashlib.sha256(p.read_bytes()).hexdigest()
    print(json.dumps({"冻结时刻": plan["冻结时刻"], "上游状态": st,
                      "发现的组合数": len(combos), "策略文件数": len(rows),
                      "计划SHA256": h}, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
